const dicts: Record<Lang, Dict> = { en, ar, hi };

export const LANGUAGES: { code: Lang; name: string; rtl: boolean }[] = [
  { code: 'en', name: 'English', rtl: false },
  { code: 'ar', name: 'العربية', rtl: true },
  { code: 'hi', name: 'हिन्दी', rtl: false },
];

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>) {
  let s = dicts[lang]?.[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function useT() {
  const lang = useUiStore((s) => s.language);
  return useCallback((key: TKey, vars?: Record<string, string | number>) => translate(lang, key, vars), [lang]);
}
