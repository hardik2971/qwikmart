import 'package:flutter/material.dart';

/// Lightweight map-based localisation (en / ar / hi). Arabic is RTL — the
/// directionality comes from [GlobalWidgetsLocalizations] automatically.
class AppLocalizations {
  AppLocalizations(this.locale);
  final Locale locale;

  static const supportedLocales = [Locale('en'), Locale('ar'), Locale('hi')];
  static const languageNames = {'en': 'English', 'ar': 'العربية', 'hi': 'हिन्दी'};

  static const LocalizationsDelegate<AppLocalizations> delegate = _Delegate();

  /// Last loaded localisation – for code without a BuildContext (error messages).
  static AppLocalizations current = AppLocalizations(const Locale('en'));

  static AppLocalizations of(BuildContext context) =>
      Localizations.of<AppLocalizations>(context, AppLocalizations) ?? AppLocalizations(const Locale('en'));

  String t(String key) => _strings[locale.languageCode]?[key] ?? _strings['en']![key] ?? key;

  static const Map<String, Map<String, String>> _strings = {
    'en': _en,
    'ar': _ar,
    'hi': _hi,
  };
}

class _Delegate extends LocalizationsDelegate<AppLocalizations> {
  const _Delegate();
  @override
  bool isSupported(Locale locale) => ['en', 'ar', 'hi'].contains(locale.languageCode);
  @override
  Future<AppLocalizations> load(Locale locale) async => AppLocalizations.current = AppLocalizations(locale);
  @override
  bool shouldReload(covariant LocalizationsDelegate<AppLocalizations> old) => false;
}

extension L10nX on BuildContext {
  String tr(String key) => AppLocalizations.of(this).t(key);

  /// Translates an order/return status key such as `out_for_delivery`.
  String trStatus(String status) {
    final v = AppLocalizations.of(this).t('status_$status');
    if (v != 'status_$status') return v;
    return status
        .replaceAll('_', ' ')
        .split(' ')
        .where((w) => w.isNotEmpty)
        .map((w) => w[0].toUpperCase() + w.substring(1))
        .join(' ');
  }
}

